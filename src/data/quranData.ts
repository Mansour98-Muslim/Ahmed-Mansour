export function getSurahsByJuz(): QuranJuz[] {
  const result: QuranJuz[] = [];
  for (let j = 1; j <= 30; j++) {
    result.push({
      juzNumber: j,
      name: JUZ_NAMES[j - 1] || `الجزء ${j}`,
      surahs: QURAN_SURAHS.filter((s) => s.juzNumber === j),
    });
  }
  return result;
}
